#!/usr/bin/env bash
# One-command environment recovery after a sandbox recycle.
#
# A recycle wipes gitignored artifacts under elvictoria/backend (node_modules,
# .env). This script rebuilds them idempotently:
#   1. backend/.env   — regenerated (fresh JWT secrets each time; users just
#                       log in again, no data impact)
#   2. node_modules   — npm install when missing
#   3. prisma client  — regenerated when missing
#   4. migrations     — applied (no-op when already applied)
#   5. bank account name setting — filled when blank
# The local PostgreSQL itself is started separately: bash scripts/pglocal.sh
#
# Usage: bash scripts/rebuild_env.sh
set -euo pipefail

BACKEND=/home/z/my-project/elvictoria/backend

# ---- 1. backend .env (only when missing) ----
if [ ! -f "$BACKEND/.env" ]; then
  echo "[rebuild] writing backend/.env"
  JWT1=$(openssl rand -hex 24)
  JWT2=$(openssl rand -hex 24)
  cat > "$BACKEND/.env" <<EOF
# ELVICTORIA backend — generated by scripts/rebuild_env.sh.
# The original remote (Neon) connection string was lost with the pre-recycle
# .env; the app runs on the sandbox-local PostgreSQL (scripts/pglocal.sh).
# To restore the original data, set DATABASE_URL / DATABASE_DIRECT_URL back
# to the Neon pooler/direct strings.

NODE_ENV=development
PORT=3030

DATABASE_URL=postgresql://elvictoria@127.0.0.1:5432/elvictoria
DATABASE_DIRECT_URL=postgresql://elvictoria@127.0.0.1:5432/elvictoria

# Cloudflare R2 (S3-compatible). Placeholders — uploads are inactive in dev.
R2_BUCKET=your-bucket
R2_ACCESS_KEY_ID=your-access-key-id
R2_SECRET_ACCESS_KEY=your-secret-access-key
R2_S3_ENDPOINT=https://ACCOUNT_ID.r2.cloudflarestorage.com
R2_PUBLIC_BASE_URL=https://pub-xxxx.r2.dev

# Flutterwave v3. Test keys only until go-live.
FLW_SECRET_KEY=FLWSECK_TEST-xxxx-X
FLW_PUBLIC_KEY=
FLW_WEBHOOK_SECRET=
FLW_ENVIRONMENT=test

# Auth
JWT_SECRET=$JWT1
JWT_ACCESS_TTL=900
REFRESH_TTL_DAYS=30

# CORS / absolute links
CORS_ORIGINS=http://localhost:3000
FRONTEND_URL=http://localhost:3000
EOF
else
  echo "[rebuild] .env exists"
fi

# ---- 2. node_modules ----
if [ ! -d "$BACKEND/node_modules/.bin" ] || [ -z "$(ls "$BACKEND/node_modules/.bin" 2>/dev/null)" ]; then
  echo "[rebuild] npm install (backend)"
  (cd "$BACKEND" && npm install 2>&1 | tail -1)
else
  echo "[rebuild] node_modules present"
fi

# ---- 3. prisma client ----
if [ ! -d "$BACKEND/node_modules/.prisma/client" ]; then
  echo "[rebuild] prisma generate"
  (cd "$BACKEND" && npx prisma generate 2>&1 | tail -1)
else
  echo "[rebuild] prisma client present"
fi

# ---- 4. migrations ----
echo "[rebuild] prisma migrate deploy"
(cd "$BACKEND" && npx prisma migrate deploy 2>&1 | tail -2)

# ---- 5. bank account name ----
node /home/z/my-project/scripts/seed_bank_name.js

echo "[rebuild] done"
