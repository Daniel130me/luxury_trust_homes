import { mkdir, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { env } from "../config/env.js";
import { buildImageKey, publicUrl, putObject, deleteObject } from "./r2.js";

/**
 * Media storage driver for listing photos and videos.
 *
 * NON-STANDARD: when the R2 credentials are still the development
 * placeholders, files are stored on local disk under backend/media and
 * served by this backend at /api/media/*, so uploads work in the sandbox
 * without cloud credentials. With real R2 credentials configured, the exact
 * same call stores to R2 and returns the public r2.dev URL — callers (the
 * upload routes and the seed scripts) are unaffected by the driver choice.
 *
 * Keys are always generated by buildMediaKey (no user-supplied path
 * segments), so local writes cannot traverse outside MEDIA_DIR.
 */
export const MEDIA_DIR = join(process.cwd(), "media");

export function isR2Configured(): boolean {
  const bucket = env.R2_BUCKET.trim();
  const base = env.R2_PUBLIC_BASE_URL;
  return (
    bucket.length > 0 &&
    bucket !== "your-bucket" &&
    !base.includes("pub-xxxx") &&
    !base.includes("ACCOUNT_ID")
  );
}

/** Store one media object under `key`. */
export async function putMedia(
  key: string,
  body: Buffer,
  contentType: string,
): Promise<void> {
  if (isR2Configured()) {
    await putObject(key, body, contentType);
    return;
  }
  const target = join(MEDIA_DIR, key);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, body);
}

/** Delete one media object. Missing local files are ignored (idempotent). */
export async function deleteMedia(key: string): Promise<void> {
  if (isR2Configured()) {
    await deleteObject(key);
    return;
  }
  await rm(join(MEDIA_DIR, key), { force: true });
}

/** Public delivery URL for a stored object (relative for the local driver). */
export function mediaPublicUrl(key: string): string {
  if (isR2Configured()) return publicUrl(key);
  return `/api/media/${key}`;
}

export { buildImageKey as buildMediaKey };

